#!/usr/bin/env python3
"""CMSIS Arm-FVP model shim: copy artifacts, then launch only inside linuxvm."""
import datetime
import hashlib
import json
import os
from pathlib import Path
import shlex
import shutil
import subprocess
import sys
import uuid

root = Path(__file__).resolve().parent.parent
args = sys.argv[1:]
if '-D' in args or '--plugin' in args:
    sys.exit('This VM model has no GDBServer plugin. Use CMSIS Run for headless validation.')
if len(args) != 4 or args[0] != '-f' or args[2] != '-a':
    sys.exit('Expected: -f <config> -a <elf> (generated by the CMSIS Arm-FVP adapter)')
config = Path(args[1]).resolve()
image = Path(args[3]).resolve()
run_id = str(uuid.uuid4())
shared = Path(os.environ.get('FVP_SHARED_DIR', '/Volumes/Ext/VM_SharedFolder'))
folder = shared / 'lean4_for_embedded' / run_id
folder.mkdir(parents=True)
shutil.copy2(config, folder / 'fvp.cfg')
shutil.copy2(image, folder / 'app.elf')
launch = '''#!/usr/bin/env bash
set -euo pipefail
ulimit -c 0
model="${FVP_MODEL:-$HOME/FVP_Corstone_SSE-300/models/Linux64_armv8l_GCC-9.3/FVP_Corstone_SSE-300_Ethos-U55}"
exec timeout --kill-after=5s 30s stdbuf -oL -eL "$model" -f fvp.cfg -a cpu0=app.elf
'''
(folder / 'launch.sh').write_text(launch)
vm_shared = os.environ.get('FVP_VM_SHARED_DIR', 'macshared')
remote_folder = vm_shared + '/lean4_for_embedded/' + run_id
command = 'cd ' + shlex.quote(remote_folder) + ' && bash launch.sh'
completed = subprocess.run(['ssh', '-o', 'BatchMode=yes', '-o', 'ConnectTimeout=10',
                            os.environ.get('FVP_SSH_HOST', 'linuxvm'), command],
                           text=True, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, timeout=45)
if completed.returncode == 0 and ('FAIL:' in completed.stdout or 'Failed to write bytes' in completed.stdout):
    completed.returncode = 1
print(completed.stdout, end='', flush=True)
evidence = root / '.build/evidence'
evidence.mkdir(parents=True, exist_ok=True)
record = {'utc': datetime.datetime.now(datetime.timezone.utc).isoformat(),
          'image': str(image.relative_to(root)),
          'config': str(config.relative_to(root)), 'config_sha256': hashlib.sha256(config.read_bytes()).hexdigest(),
          'sha256': hashlib.sha256(image.read_bytes()).hexdigest(),
          'run_id': run_id, 'returncode': completed.returncode, 'output': completed.stdout}
(evidence / (image.parent.parent.name + ('-' + image.parent.name if image.parent.name != 'Debug' else '') + '-' + image.stem + '.json')).write_text(json.dumps(record, indent=2) + '\n')
shutil.rmtree(folder)
sys.exit(completed.returncode)
