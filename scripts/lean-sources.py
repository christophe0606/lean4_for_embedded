#!/usr/bin/env python3
"""Generate a CMake manifest of stock Lean C output and its module dependency closure.

Lake builds only the :c facet for package modules. Builtin modules are generated
from the matching upstream source, never linked from host archives. Every real
module initializer is kept; missing modules and unsupported runtime APIs fail.
"""
import argparse
import hashlib
import json
import shutil
from pathlib import Path
import re
import subprocess
import sys

parser = argparse.ArgumentParser()
parser.add_argument('--root', required=True, type=Path)
parser.add_argument('--upstream', required=True, type=Path)
parser.add_argument('--output', required=True, type=Path)
parser.add_argument('--lake', required=True)
parser.add_argument('--module', action='append', required=True)
a = parser.parse_args()
a.root = a.root.resolve()
a.output.mkdir(parents=True, exist_ok=True)
pin = json.loads((a.root / 'upstream.json').read_text(encoding='utf-8'))
shared_c = a.root / '.build/lean-c' / pin['commit']

def command(args):
    result = subprocess.run(args, cwd=a.root, text=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
    if result.returncode:
        raise RuntimeError(' | '.join(line for line in (result.stdout + result.stderr).splitlines() if 'error:' in line) or 'Lean generation failed')
    if result.stderr:
        print(result.stderr, end='', file=sys.stderr)
    return result.stdout.strip()

seen = set()
sources = []
inputs = []
initializers = {}

def visit(module):
    if module in seen:
        return
    seen.add(module)
    standard = a.upstream / 'src' / Path(*module.split('.')).with_suffix('.lean')
    if standard.exists() and module.split('.')[0] in ('Init', 'Std', 'Lean'):
        source = standard
        relative = Path(*module.split('.')).with_suffix('.c')
        output = shared_c / relative
        output.parent.mkdir(parents=True, exist_ok=True)
        digest = hashlib.sha256(source.read_bytes() + (a.root / 'lean-toolchain').read_bytes()).hexdigest()
        stamp = output.with_suffix('.sha256')
        legacy = a.output / relative
        if not output.exists() and legacy.exists() and legacy.with_suffix('.sha256').exists() and legacy.with_suffix('.sha256').read_text(encoding='utf-8') == digest:
            shutil.copy2(legacy, output)
            stamp.write_text(digest, encoding='utf-8')
        if not output.exists() or not stamp.exists() or stamp.read_text(encoding='utf-8') != digest:
            command([a.lake, 'env', 'lean', '--root=' + str(a.upstream / 'src'), '-c', str(output), str(source)])
            stamp.write_text(digest, encoding='utf-8')
    else:
        output = Path(command([a.lake, '-q', '--no-cache', 'query', '+' + module + ':c']))
        if not output.is_absolute():
            output = a.root / output
        source = Path(command([a.lake, '-q', 'query', '+' + module + ':lean']))
        if not source.is_absolute():
            source = a.root / source
    if not source.exists() or not output.exists():
        raise RuntimeError('No source/C artifact for ' + module)
    inputs.append(source.resolve())
    text = output.read_text(encoding='utf-8')
    candidates = re.findall(r'LEAN_EXPORT lean_object\s*\*\s*(runtime_initialize_[A-Za-z0-9_]+)\(uint8_t builtin\)', text)
    has_runtime_initializer = bool(candidates)
    if not candidates:
        candidates = re.findall(r'LEAN_EXPORT lean_object\s*\*\s*(initialize_[A-Za-z0-9_]+)\(uint8_t builtin\)', text)
    if len(candidates) != 1:
        raise RuntimeError('Expected one module initializer in ' + str(output))
    initializers[module] = candidates[0]
    match = re.search(r'^// Imports: (.*)$', text, re.M)
    if match:
        for meta, dependency in re.findall(r'\b(?:(meta)\s+)?import\s+(?:all\s+)?([\w.]+)', match.group(1)):
            if not meta or not has_runtime_initializer:
                visit(dependency)
    sources.append(output.resolve())

try:
    for module in a.module:
        visit(module)
    header = '#pragma once\n#include <lean/lean.h>\n#ifdef __cplusplus\nextern "C" {\n#endif\n'
    for module in a.module:
        header += 'lean_object * ' + initializers[module] + '(uint8_t builtin);\n'
    header += 'static inline lean_object * lean_app_initialize(uint8_t builtin) {\n  lean_object * result;\n'
    for module in a.module:
        header += '  result = ' + initializers[module] + '(builtin);\n  if (lean_io_result_is_error(result)) return result;\n  lean_dec(result);\n'
    header += '  return lean_io_result_mk_ok(lean_box(0));\n}\n#ifdef __cplusplus\n}\n#endif\n'
    (a.output / 'lean_app_init.h').write_text(header, encoding='utf-8')
    manifest = '# Generated by scripts/lean-sources.py; do not edit.\n'
    for variable, paths in [('LEAN_C_FILES', sources), ('LEAN_INPUT_FILES', inputs)]:
        manifest += 'set(' + variable + '\n'
        manifest += ''.join('  "' + str(path).replace('\\', '/') + '"\n' for path in paths)
        manifest += ')\n'
    manifest += 'set(LEAN_MODULE_COUNT ' + str(len(seen)) + ')\n'
    path = a.output / 'sources.cmake'
    if not path.exists() or path.read_text(encoding='utf-8') != manifest:
        path.write_text(manifest, encoding='utf-8')
    (a.output / 'modules.txt').write_text('\n'.join(sorted(seen)) + '\n', encoding='utf-8')
except Exception as error:
    sys.exit(str(Path(__file__).resolve()) + ':1:1: error: ' + str(error))
